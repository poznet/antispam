/**
 * "Zmień na: Wszystkie skrzynki" on the admin rule lists: one rule / checked
 * rules / every rule of a mailbox become global (owner '*'), duplicates merge
 * into an existing global rule, blacklist rules get the retroactive pass, SSH
 * agents get a rules sync, admin only, POST + CSRF.
 */
class RuleMakeGlobalTest extends KernelTestCase
{
    private JobsDatabase $db;
    private RecordingAuditLogger $audit;
    private Session $session;
    /** @var string[] redirect targets generated by the controller */
    private array $redirects = [];

    protected function setUp(): void
    {
        $this->db = new JobsDatabase();
        $this->audit = new RecordingAuditLogger();
        foreach ([
            ['jan@firma.pl', Account::CONNECTION_SSH, true],
            ['ola@firma.pl', Account::CONNECTION_SSH, true],
            ['old@firma.pl', Account::CONNECTION_SSH, false],
            ['imap@firma.pl', Account::CONNECTION_IMAP, false],
        ] as [$email, $type, $deployed]) {
            $this->db->em->persist((new Account())->setName($email)->setEmail($email)->setConnectionType($type)->setAgentDeployed($deployed));
        }
        $this->db->em->flush();
    }

    private function globalizer(): RuleGlobalizer
    {
        return new RuleGlobalizer($this->db->em, new DeferredRetroactivePass($this->db->queue), new DeferredAgentSync($this->db->em, $this->db->queue), $this->audit);
    }

    private function rule(string $class, string $owner, string $value, int $counter = 0, string $type = 'exact', int $score = 10): object
    {
        $rule = new $class();
        $rule->setEmail($owner)->setPatternType($type)->setCounter($counter);
        match ($class) {
            Blacklist::class => $rule->setHost($value)->setScore($score),
            Whitelist::class => $rule->setHost($value),
            EmailBlacklist::class => $rule->setBlacklistemail($value)->setScore($score),
            EmailWhitelist::class => $rule->setWhitelistemail($value),
        };
        $this->db->em->persist($rule);
        $this->db->em->flush();
        return $rule;
    }

    private function jobs(): array
    {
        return $this->db->em->getConnection()->fetchAllAssociative('SELECT type, payload, mailbox, account_id FROM antispam_job ORDER BY id');
    }

    private function controller(string $class): AbstractController
    {
        $config = $this->createMock(ConfigService::class);
        $config->method('get')->willReturn(null);
        $ownership = new RuleOwnership($this->db->em, $config);
        $controller = match ($class) {
            DomainBlacklistController::class, EmailBlacklistController::class => new $class($this->db->em, $ownership, new DeferredRetroactivePass($this->db->queue), $this->globalizer()),
            default => new $class($this->db->em, $ownership, $this->globalizer()),
        };

        $csrf = $this->createMock(CsrfTokenManagerInterface::class);
        $csrf->method('isTokenValid')->willReturnCallback(fn(CsrfToken $t) => $t->getId() === 'list_rules' && $t->getValue() === 'good');
        $router = $this->createMock(RouterInterface::class);
        $router->method('generate')->willReturnCallback(function ($name, $params = []) {
            return $this->redirects[] = '/' . $name . ($params ? '?' . http_build_query($params) : '');
        });
        $this->session = new Session(new MockArraySessionStorage());
        $request = new Request();
        $request->setSession($this->session);
        $stack = new RequestStack();
        $stack->push($request);
        $controller->setContainer(new ServiceLocator([
            'security.csrf.token_manager' => fn() => $csrf,
            'router' => fn() => $router,
            'request_stack' => fn() => $stack,
        ]));
        return $controller;
    }

    private function post(array $data): Request
    {
        return Request::create('/x', 'POST', $data);
    }

    // ---- RuleGlobalizer ----------------------------------------------------

    public function testMovedRuleKeepsIdCounterAndScore()
    {
        $rule = $this->rule(Blacklist::class, 'jan@firma.pl', 'spam.example', 7, 'exact', 25);
        $result = $this->globalizer()->makeGlobal([$rule]);

        $this->assertSame([1, 0], [$result['moved'], $result['merged']]);
        $this->db->em->clear();
        $stored = $this->db->em->find(Blacklist::class, $rule->getId());
        $this->assertSame(['*', 7, 25], [$stored->getEmail(), (int)$stored->getCounter(), $stored->getScore()]);
    }

    public function testDuplicateMergesIntoTheExistingGlobalRule()
    {
        $global = $this->rule(EmailWhitelist::class, '*', 'friend@x.pl', 3);
        $local = $this->rule(EmailWhitelist::class, 'jan@firma.pl', 'friend@x.pl', 4);
        $otherType = $this->rule(EmailWhitelist::class, 'jan@firma.pl', 'friend@x.pl', 1, 'wildcard');
        $localId = $local->getId();

        $result = $this->globalizer()->makeGlobal([$local, $otherType]);

        $this->assertSame([1, 1], [$result['moved'], $result['merged']]);
        $this->db->em->clear();
        $this->assertNull($this->db->em->find(EmailWhitelist::class, $localId), 'the mailbox copy is removed, no duplicate');
        $this->assertSame(7, (int)$this->db->em->find(EmailWhitelist::class, $global->getId())->getCounter(), 'hit counters are added');
        $this->assertSame('*', $this->db->em->find(EmailWhitelist::class, $otherType->getId())->getEmail(), 'another pattern type is a different rule');
        $this->assertCount(2, $this->db->em->getRepository(EmailWhitelist::class)->findAll());
    }

    public function testTwoMailboxCopiesInOneBatchBecomeOneGlobalRule()
    {
        $a = $this->rule(Whitelist::class, 'jan@firma.pl', 'partner.pl', 2);
        $b = $this->rule(Whitelist::class, 'ola@firma.pl', 'partner.pl', 5);

        $result = $this->globalizer()->makeGlobal([$a, $b]);

        $this->assertSame([1, 1], [$result['moved'], $result['merged']]);
        $this->db->em->clear();
        $all = $this->db->em->getRepository(Whitelist::class)->findAll();
        $this->assertCount(1, $all);
        $this->assertSame(['*', 7], [$all[0]->getEmail(), (int)$all[0]->getCounter()]);
    }

    public function testBlacklistQueuesARetroactivePassOverEveryMailboxAndSshSync()
    {
        $rule = $this->rule(EmailBlacklist::class, 'jan@firma.pl', 'spammer@x.ru');
        $result = $this->globalizer()->makeGlobal([$rule]);

        $this->assertCount(1, $result['retroactive']);
        $this->assertSame(2, $result['synced'], 'every deployed SSH agent, not only the old owner\'s');
        $jobs = $this->jobs();
        $this->assertSame(BackgroundJob::TYPE_RULE_RETROACTIVE, $jobs[0]['type']);
        $this->assertSame('{"rule":"email_blacklist","id":' . $rule->getId() . '}', $jobs[0]['payload']);
        $this->assertSame('*', $jobs[0]['mailbox'], 'the job runs for the global rule - RetroactiveSpamService covers every account');
        $this->assertSame([BackgroundJob::TYPE_ACCOUNT_SYNC, BackgroundJob::TYPE_ACCOUNT_SYNC], array_column(array_slice($jobs, 1), 'type'));
    }

    public function testWhitelistAndMergedBlacklistGetNoRetroactivePass()
    {
        $this->rule(Blacklist::class, '*', 'spam.example');
        $merged = $this->rule(Blacklist::class, 'jan@firma.pl', 'spam.example');
        $white = $this->rule(Whitelist::class, 'jan@firma.pl', 'ok.example');

        $result = $this->globalizer()->makeGlobal([$merged, $white]);

        $this->assertSame([], $result['retroactive'], 'the global rule already applied everywhere');
        $this->assertSame([BackgroundJob::TYPE_ACCOUNT_SYNC], array_values(array_unique(array_column($this->jobs(), 'type'))));
    }

    public function testAlreadyGlobalRuleIsLeftAloneWithoutSideEffects()
    {
        $rule = $this->rule(Blacklist::class, '*', 'spam.example');
        $result = $this->globalizer()->makeGlobal([$rule]);

        $this->assertSame([0, 0, 1], [$result['moved'], $result['merged'], $result['unchanged']]);
        $this->assertSame([], $this->jobs());
        $this->assertSame([], $this->audit->entries);
    }

    public function testEveryChangedRuleIsAudited()
    {
        $this->rule(Whitelist::class, '*', 'partner.pl');
        $merged = $this->rule(Whitelist::class, 'jan@firma.pl', 'partner.pl');
        $moved = $this->rule(Blacklist::class, 'ola@firma.pl', 'spam.example', 0, 'wildcard', 15);
        $mergedId = $merged->getId();

        $this->globalizer()->makeGlobal([$merged, $moved]);

        $this->assertCount(2, $this->audit->entries);
        [$a, $b] = $this->audit->entries;
        $this->assertSame(['rule.make_global', 'whitelist', $mergedId, 'partner.pl', '*'], [$a['action'], $a['targetType'], $a['targetId'], $a['label'], $a['mailbox']]);
        $this->assertSame(['from' => 'jan@firma.pl', 'merged' => true, 'pattern_type' => 'exact'], $a['details']);
        $this->assertSame(['from' => 'ola@firma.pl', 'merged' => false, 'pattern_type' => 'wildcard', 'score' => 15], $b['details']);
    }

    // ---- Controllers -------------------------------------------------------

    public static function lists(): array
    {
        return [
            [DomainBlacklistController::class, Blacklist::class, 'antispam_blacklist'],
            [EmailBlacklistController::class, EmailBlacklist::class, 'antispam_emailblacklist'],
            [WhitelistController::class, Whitelist::class, 'antispam_whitelist'],
            [EmailWhitelistController::class, EmailWhitelist::class, 'antispam_emailwhitelist'],
        ];
    }

    #[DataProvider('lists')]
    public function testSingleRuleAction(string $controllerClass, string $entity, string $route)
    {
        $rule = $this->rule($entity, 'jan@firma.pl', 'a.example');
        $other = $this->rule($entity, 'jan@firma.pl', 'b.example');
        $controller = $this->controller($controllerClass);

        $response = $controller->makeGlobalAction($rule->getId(), $this->post(['_token' => 'good', 'return_owner' => 'jan@firma.pl']));

        $this->assertSame('/' . $route . '_index?owner=jan%40firma.pl', $response->getTargetUrl(), 'back to the filtered list');
        $this->assertSame('*', $rule->getEmail());
        $this->assertSame('jan@firma.pl', $other->getEmail());
        $this->assertNotEmpty($this->session->getFlashBag()->get('success'));
    }

    #[DataProvider('lists')]
    public function testBulkCheckedAndAllOfMailbox(string $controllerClass, string $entity, string $route)
    {
        $a = $this->rule($entity, 'jan@firma.pl', 'a.example');
        $b = $this->rule($entity, 'jan@firma.pl', 'b.example');
        $c = $this->rule($entity, 'ola@firma.pl', 'c.example');
        $d = $this->rule($entity, 'ola@firma.pl', 'd.example');
        $controller = $this->controller($controllerClass);

        $controller->makeGlobalBulkAction($this->post(['_token' => 'good', 'ids' => [(string)$a->getId(), (string)$c->getId(), 'x']]));
        $this->assertSame(['*', 'jan@firma.pl', '*', 'ola@firma.pl'], [$a->getEmail(), $b->getEmail(), $c->getEmail(), $d->getEmail()]);

        $response = $controller->makeGlobalBulkAction($this->post(['_token' => 'good', 'all_of' => 'jan@firma.pl', 'return_owner' => 'jan@firma.pl']));
        $this->assertSame(['*', '*', 'ola@firma.pl'], [$b->getEmail(), $c->getEmail(), $d->getEmail()]);
        $this->assertSame('/' . $route . '_index?owner=%2A', $response->getTargetUrl(), 'the mailbox filter is empty now - show the global rules');
    }

    public function testBulkWithNothingSelectedChangesNothing()
    {
        $rule = $this->rule(Blacklist::class, 'jan@firma.pl', 'a.example');
        $controller = $this->controller(DomainBlacklistController::class);

        $controller->makeGlobalBulkAction($this->post(['_token' => 'good']));
        $controller->makeGlobalBulkAction($this->post(['_token' => 'good', 'all_of' => '*']));

        $this->assertSame('jan@firma.pl', $rule->getEmail());
        $this->assertSame([], $this->jobs());
    }

    public function testBlacklistControllerFlashesTheQueuedJobs()
    {
        $rule = $this->rule(Blacklist::class, 'jan@firma.pl', 'a.example');
        $this->controller(DomainBlacklistController::class)->makeGlobalAction($rule->getId(), $this->post(['_token' => 'good']));

        $info = implode(' ', $this->session->getFlashBag()->get('info'));
        $this->assertStringContainsString('ostatnie 30 dni, wszystkie konta', $info);
        $this->assertStringContainsString('agentów SSH w tle (kont: 2)', $info);
    }

    #[DataProvider('lists')]
    public function testCsrfIsRequired(string $controllerClass, string $entity)
    {
        $rule = $this->rule($entity, 'jan@firma.pl', 'a.example');
        $controller = $this->controller($controllerClass);
        foreach ([[], ['_token' => 'bad']] as $token) {
            foreach (['one', 'bulk'] as $action) {
                try {
                    $action === 'one'
                        ? $controller->makeGlobalAction($rule->getId(), $this->post($token))
                        : $controller->makeGlobalBulkAction($this->post($token + ['ids' => [$rule->getId()]]));
                    $this->fail('make-global without a valid CSRF token must be refused');
                } catch (AccessDeniedException) {
                }
            }
        }
        $this->assertSame('jan@firma.pl', $rule->getEmail());
    }

