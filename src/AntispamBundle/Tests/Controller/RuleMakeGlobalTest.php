    #[DataProvider('paths')]
    public function testRoutesArePostOnlyAndAdminOnly(string $path)
    {
        self::bootKernel();
        $c = self::getContainer();
        [$attributes] = $c->get('security.access_map')->getPatterns(Request::create($path, 'POST'));
        $this->assertSame(['ROLE_ADMIN'], $attributes);
        $route = $c->get('router')->matchRequest(Request::create($path, 'POST'));
        $this->assertStringEndsWith('make_global' . (str_ends_with($path, '/1') ? '' : '_bulk'), $route['_route']);
        $this->assertSame(['POST'], $c->get('router')->getRouteCollection()->get($route['_route'])->getMethods());
    }

    #[DataProvider('lists')]
    public function testRoleUserIsRefusedByTheController(string $controllerClass)
    {
        self::bootKernel();
        $c = self::getContainer();
        $jan = (new User())->setUsername('jan')->setRole(User::ROLE_USER);
        $c->get('security.token_storage')->setToken(new UsernamePasswordToken($jan, 'main', $jan->getRoles()));
        foreach (['makeGlobalAction' => [1, new Request()], 'makeGlobalBulkAction' => [new Request()]] as $method => $args) {
            try {
                $c->get('controller.is_granted_attribute_listener')->onKernelControllerArguments(new ControllerArgumentsEvent(
                    self::$kernel, [$c->get($controllerClass), $method], $args, new Request(), HttpKernelInterface::MAIN_REQUEST));
                $this->fail($method . ' must be refused to ROLE_USER');
            } catch (AccessDeniedException) {
                $this->addToAssertionCount(1);
            }
        }
    }

    public function testUserAreaHasNoMakeGlobal()
    {
        $this->assertFalse(method_exists(MyRulesController::class, 'makeGlobalAction'));
        self::bootKernel();
        foreach (self::getContainer()->get('router')->getRouteCollection() as $name => $route) {
            if (str_starts_with($route->getPath(), '/my')) {
                $this->assertStringNotContainsString('global', $name . $route->getPath());
            }
        }
    }

    public function testListTemplateShowsTheActions()
    {
        self::bootKernel();
        $request = Request::create('/');
        $request->setSession(new Session(new MockArraySessionStorage()));
        self::getContainer()->get('request_stack')->push($request);
        $local = (new Blacklist())->setEmail('jan@firma.pl')->setHost('a.example')->setPatternType('exact')->setScore(10)->setCounter(0);
        $global = (new Blacklist())->setEmail('*')->setHost('b.example')->setPatternType('exact')->setScore(10)->setCounter(0);
        (new \ReflectionProperty(Blacklist::class, 'id'))->setValue($local, 11);
        (new \ReflectionProperty(Blacklist::class, 'id'))->setValue($global, 12);

        $html = self::getContainer()->get('twig')->render('@Antispam/DomainBlacklist/index.html.twig', [
            'list' => [$local, $global], 'owners' => ['*' => 'Wszystkie skrzynki', 'jan@firma.pl' => 'jan@firma.pl'],
            'choices' => ['*' => 'Wszystkie skrzynki'], 'default_owner' => '*', 'owner_filter' => 'jan@firma.pl',
        ]);

        $this->assertStringContainsString('action="/domainblacklst/global/11"', $html);
        $this->assertStringNotContainsString('/domainblacklst/global/12', $html, 'no button for a rule that is already global');
        $this->assertStringContainsString('action="/domainblacklst/global" id="rules-make-global"', $html);
        $this->assertStringContainsString('name="ids[]" value="11" form="rules-make-global"', $html);
        $this->assertStringContainsString('name="all_of" value="jan@firma.pl"', $html);
        $this->assertStringContainsString('będzie działać dla KAŻDEJ skrzynki', $html);
        $this->assertStringContainsString('trafią do SPAM', $html, 'blacklist dialog mentions the retroactive pass');
        $this->assertStringContainsString('js/rule-select.js', $html);
    }
